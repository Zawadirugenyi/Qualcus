#!/usr/bin/env node
// ============================================================
//  Prepare the production environment files.
//
//  npm run deploy:prepare -- --sqlite
//  npm run deploy:prepare -- --db "postgresql://..."
//
//  Options: --sqlite | --db <uri> | --site <url> | --email <addr> | --password <pw>
//
//  Creates:
//    .env.production        -> settings for the React build
//    cms/.env.production    -> settings for the CMS (systemd reads this file)
// ============================================================
import { randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2)
const arg = (name, fallback) => {
  const i = args.indexOf(name)
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback
}

const useSQLite = args.includes('--sqlite')
const dbUri = useSQLite
  ? arg('--db', 'file:/home/qualcus/app/cms/qualcus.db')
  : arg('--db', process.env.DATABASE_URI)
const siteUrl = (arg('--site', process.env.SITE_URL || 'https://qualcus.com')).replace(/\/+$/, '')
const adminEmail = arg('--email', process.env.ADMIN_EMAIL || 'admin@qualcus.com')
const adminPassword = arg(
  '--password',
  process.env.ADMIN_PASSWORD || randomBytes(9).toString('base64url'),
)

if (!dbUri) {
  console.error(
    'Missing database.\n' +
      '  SQLite on the server:  npm run deploy:prepare -- --sqlite\n' +
      '  Managed Postgres:      npm run deploy:prepare -- --db "postgresql://user:pass@host:5432/db"',
  )
  process.exit(1)
}

const isSQLite = /^(file:|sqlite:)/i.test(dbUri)
const isPostgres = /^postgres(ql)?:\/\//i.test(dbUri)

if (!isSQLite && !isPostgres) {
  console.error('DATABASE_URI must start with "file:" (SQLite) or "postgresql://".')
  process.exit(1)
}

if (isSQLite && /^file:\.[/\\]/.test(dbUri)) {
  console.warn(
    'WARNING: relative SQLite path. The server runs from /home/qualcus/app/cms, so\n' +
      '         use "file:/home/qualcus/app/cms/qualcus.db" (absolute).',
  )
}

const rootEnv = `# ============================================================
#  Production build settings — generated by scripts/prepare-deploy.mjs
# ============================================================
VITE_SITE_URL=${siteUrl}
VITE_API_URL=
VITE_CMS_URL=${siteUrl}
`

const cmsEnv = `# ============================================================
#  Production settings for the CMS — generated by scripts/prepare-deploy.mjs
#  Loaded by systemd (EnvironmentFile) and by the Payload CLI.
# ============================================================
DATABASE_URI="${dbUri}"
PAYLOAD_SECRET="${process.env.PAYLOAD_SECRET || randomBytes(48).toString('hex')}"
NEXT_PUBLIC_SITE_URL=${siteUrl}
ADMIN_EMAIL=${adminEmail}
ADMIN_PASSWORD=${adminPassword}
CMS_ORIGIN=${siteUrl},${siteUrl.replace('https://', 'https://www.')}
MEDIA_DIR=/home/qualcus/app/cms/media
`

writeFileSync(new URL('../.env.production', import.meta.url), rootEnv)
writeFileSync(new URL('../cms/.env.production', import.meta.url), cmsEnv)

console.log('Created:')
console.log('  .env.production')
console.log('  cms/.env.production')
console.log('')
console.log(`  site            ${siteUrl}`)
console.log(`  database        ${dbUri.replace(/:[^:@/]+@/, ':***@')}`)
console.log(`  admin email     ${adminEmail}`)
console.log(
  `  seed password   ${adminPassword}`,
)
console.log('                  (only used if the database is created from scratch;')
console.log('                   a copied SQLite database keeps its existing password)')
console.log('')
console.log('Next:  npm run deploy -- root@YOUR_SERVER_IP')
console.log(
  isSQLite
    ? '       (first deploy copies cms/qualcus.db and cms/media to the server)'
    : '       (first deploy creates the tables in Postgres)',
)
